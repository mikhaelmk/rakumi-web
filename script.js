const SUPPORTED_LANGUAGES = ["en", "pt"];
const LANGUAGE_STORAGE_KEY = "rakumi-language";
const languageButtons = document.querySelectorAll("[data-lang]");
const metaDescription = document.querySelector('meta[name="description"]');

function t(language, key) {
  return translations[language]?.[key] ?? translations.en[key] ?? key;
}

function applyLanguage(language, { persist = true } = {}) {
  const nextLanguage = SUPPORTED_LANGUAGES.includes(language) ? language : "en";

  document.documentElement.lang = nextLanguage === "pt" ? "pt-BR" : "en";
  document.title = t(nextLanguage, "meta.title");
  if (metaDescription) metaDescription.content = t(nextLanguage, "meta.description");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(nextLanguage, element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = t(nextLanguage, element.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", t(nextLanguage, element.dataset.i18nAriaLabel));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", t(nextLanguage, element.dataset.i18nAlt));
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === nextLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (persist) localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.lang));
});

const storedLanguage = localStorage.getItem(LANGUAGE_STORAGE_KEY);
const browserLanguage = navigator.language?.toLowerCase().startsWith("pt") ? "pt" : "en";
applyLanguage(storedLanguage || browserLanguage, { persist: Boolean(storedLanguage) });

const progressBars = document.querySelectorAll(".progress-bar");

const revealProgress = (bar) => {
  const value = bar.dataset.progress || "0";
  bar.style.width = `${value}%`;
};

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries, instance) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;

        revealProgress(entry.target);
        instance.unobserve(entry.target);
      });
    },
    { threshold: 0.35 }
  );

  progressBars.forEach((bar) => observer.observe(bar));
} else {
  progressBars.forEach(revealProgress);
}
